test_that('browser keeps article IDs and translates codes without altering the source', {
  articles <- read.csv('data/3.meta_data/review_data/review_data.csv', colClasses='character')
  variables <- read.csv('data/matrix_codebook.csv', colClasses='character')
  topics <- read.csv('data/topics_codebook.csv', colClasses='character')
  original <- articles
  display <- review_browser_data(articles[nrow(articles):1, ],
    c('title', 'constructs_analyzed', 'study_design'), variables, topics)
  expect_identical(display$Code, sort(articles$paper_id))
  expect_identical(names(display), c('Code', 'Title', 'Analyzed constructs', 'Study design'))
  expect_true(all(nchar(display$Code) >= 4))
  expect_identical(articles, original)
  expect_equal(review_display_text('long; cross', 'study_design', variables, topics),
    'Longitudinal; Cross-sectional')
  expect_equal(review_display_text(NA_character_, 'notes', variables, topics), 'Not reported')
  expect_equal(review_display_text('unknown', 'constructs_analyzed', variables, topics), 'unknown')
  samples <- data.frame(paper_id=c('0013','0013'), seb_measure=c('bessi45','bessi192'))
  display <- review_browser_data(articles, c('seb_measure'), variables, topics, samples)
  expect_equal(display$`SEB instruments`[display$Code=='0013'], 'bessi45; bessi192')
  expect_identical(articles, original)
})

test_that('search includes hidden abstracts and readable constructs for review-only articles', {
  variables <- data.frame(column_name='academicachievement', label='Academic achievement')
  topics <- data.frame(Topic='validation', Topic_labs='Measure validation')
  articles <- data.frame(paper_id=c('0013','0048'), title=c('Skills','Other'),
    author_et_al='Fixture', final_decision=c('review','both'),
    abstract=c('A hidden abstract phrase','Something else'),
    constructs_analyzed=c('academicachievement',''), review_topics='validation')
  search <- function(query) review_search_data(articles, query, variables, topics)$paper_id
  expect_equal(search('ACADEMIC ACHIEVEMENT'), '0013')
  expect_equal(search('hidden abstract'), '0013')
  expect_equal(search('0013'), '0013')
  expect_equal(search('measure validation'), c('0013','0048'))
  expect_length(search('[literal]'), 0)
  expect_equal(search(' '), articles$paper_id)
  expect_equal(nrow(review_search_data(articles[FALSE, ], 'none', variables, topics)), 0)
})

test_that('article selection stays tied to its code when filters and columns change', {
  suppressPackageStartupMessages({ library(shiny); library(shinyjs); library(tidyverse) })
  app <- new.env()
  app$review <- read.csv('data/3.meta_data/review_data/review_data.csv', colClasses='character')
  app$admcol <- read.csv('data/matrix_codebook.csv', colClasses='character')
  app$labels_app <- setNames(app$admcol$label, app$admcol$column_name)
  app$topics_list <- read.csv('data/topics_codebook.csv', colClasses='character')
  app$combined_data <- readxl::read_excel('data/3.meta_data/meta_data/metadata.xlsx')
  sys.source('app/R/utils.R', envir=app)
  sys.source('app/R/masem_workflow.R', envir=app)
  sys.source('app/server.R', envir=app)
  testServer(app$server, {
    session$setInputs(review_columns=c('author_et_al','year','title'), review_search='')
    expect_equal(nrow(review_articles()), nrow(app$review))
    session$setInputs(revTable_rows_selected=match('0013', review_articles()$paper_id))
    expect_identical(selected_review_id(), '0013')
    expect_match(output$review_article$html, 'Ringwald')
    expect_match(output$review_article$html, 'Review only')
    session$setInputs(review_search='[no article]')
    expect_equal(nrow(review_articles()), 0L)
    expect_null(selected_review_id())
    expect_false(grepl('Ringwald', output$review_article$html))
    session$setInputs(review_search='', review_constructs='academicachievement')
    expect_true('0013' %in% review_articles()$paper_id)
    session$setInputs(review_search='Ringwald')
    expect_equal(nrow(revSelection()$filteredData), 1L)
    downloaded <- read.csv(output$downloadFiltered, colClasses='character', check.names=FALSE)
    expect_identical(downloaded$paper_id, '0013')
    expect_identical(names(downloaded), names(app$review))
    session$setInputs(revTable_rows_selected=1L)
    expect_identical(selected_review_id(), '0013')
    session$setInputs(review_columns=c('title','main_objective','constructs_analyzed'))
    expect_null(selected_review_id())
    session$setInputs(review_search='', review_constructs=character())
    expect_equal(nrow(revSelection()$filteredData), nrow(app$review))
    session$setInputs(revTable_rows_selected=match('0053', review_articles()$paper_id))
    expect_match(output$review_article$html, 'Included quantitative matrices')
    expect_match(output$review_article$html, '0053c')
    expect_match(output$review_article$html, 'Notes by quantitative matrix')
    expect_false(grepl('Quantitative exclusion reason', output$review_article$html))
  })
})
